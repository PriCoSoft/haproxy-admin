def new_site(name=""):
    return {
        "name": name, "description": "", "enabled": True, "type": "proxy",
        "routes": [], "http": False, "http1": False,
        "servers": [], "balance": "leastconn", "keepalive": False, "prefer_last": False, "cookie": "",
        "timeout_server": "", "timeout_tunnel": "", "srvtcpka": False,
        "allow_paths": [], "allow_src": [], "redirects": [], "block": False, "extra": [],
        "target": "", "keep_uri": True, "code": 302,
    }


def normalize(m):
    """Fill missing keys (older models / partial imports)."""
    base = default_model()
    out = copy.deepcopy(m) if m else {}
    for k, v in base.items():
        if k not in out:
            out[k] = copy.deepcopy(v)
        elif isinstance(v, dict):
            for k2, v2 in v.items():
                out[k].setdefault(k2, copy.deepcopy(v2))
    sites = []
    for s in out.get("sites", []):
        full = new_site()
        full.update(s)
        for r in full["routes"]:
            r.setdefault("conds", [])
        sites.append(full)
    out["sites"] = sites
    return out


# ----------------------------------------------------------------------------- embedding
def embed(text, m):
    data = base64.b64encode(zlib.compress(json.dumps(m, separators=(",", ":"), sort_keys=True).encode(), 9)).decode()
    lines = [MODEL_PREFIX + data[i:i + 100] for i in range(0, len(data), 100)]
    return text.rstrip("\n") + "\n\n" + MODEL_MARK + "\n" + "\n".join(lines) + "\n"


def extract(text):
    """Return (model or None, body without the model block)."""
    idx = text.find(MODEL_MARK)
    if idx < 0:
        return None, text
    body = text[:idx].rstrip("\n") + "\n"
    data = "".join(l[len(MODEL_PREFIX):].strip() for l in text[idx:].split("\n") if l.startswith(MODEL_PREFIX))
    try:
        m = json.loads(zlib.decompress(base64.b64decode(data)).decode())
    except (ValueError, zlib.error):
        return None, text
    return normalize(m), body


def is_model_line(line):
    return line.startswith(MODEL_PREFIX) or line == MODEL_MARK


# ----------------------------------------------------------------------------- validation
def _cidrs(values, where, errors):
    for v in values:
        try:
            ipaddress.ip_network(v, strict=False)
        except ValueError:
            errors.append(f"{where}: '{v}' is not a valid IP address or network.")


def _lines(values, where, errors):
    for l in values:
        s = l.strip()
        if not s:
            continue
        if "\n" in l or "\r" in l:
            errors.append(f"{where}: invalid line break.")
        elif s.split()[0] in SECTION_WORDS:
            errors.append(f"{where}: '{s.split()[0]}' would start a new section; use 'Raw sections' instead.")


def validate_host(h):
    return bool(HOST_PATTERN_RE.match(h)) and "**" not in h and h.strip("*.-") != ""


def validate_cond(c):
    t, v = c.get("type"), (c.get("value") or "").strip()
    if t not in COND_TYPES:
        return "unknown condition type"
    if not v:
        return "value missing"
    vals = v.split() if t in MULTI_VALUE_CONDS else [v]
    if t not in MULTI_VALUE_CONDS and len(v.split()) > 1:
        return "value must not contain spaces"
    for x in vals:
        if not TOKEN_RE.match(x) or x in ("{", "}"):
            return f"invalid value '{x}'"
        if "\\" in x and t != "path_reg":
            return "backslashes are only allowed in regular expressions"
    if t == "src":
        for x in vals:
            try:
                ipaddress.ip_network(x, strict=False)
            except ValueError:
                return f"'{x}' is not an IP address or network"
    if t in ("path_beg", "path", "path_end") and t != "path_end" and not v.startswith("/"):
        return "path must start with /"
    return None


def validate_site(s, errors, names):
    n = s.get("name", "")
    where = f"Site {n or '(new)'}"
    if not NAME_RE.match(n):
        errors.append(f"{where}: name must be 1-64 characters A-Z, a-z, 0-9, '.', '_' or '-'.")
    elif n in INTERNAL_BACKENDS:
        errors.append(f"{where}: name is reserved.")
    elif n in names:
        errors.append(f"{where}: another site has the same name.")
    names.add(n)
    if "\n" in s.get("description", "") or len(s.get("description", "")) > 200:
        errors.append(f"{where}: description must be one line (max. 200 characters).")
    if s.get("enabled") and not s["routes"]:
        errors.append(f"{where}: add at least one host name.")
    seen = set()
    for r in s["routes"]:
        h = r.get("host", "")
        if not validate_host(h):
            errors.append(f"{where}: '{h}' is not a valid host name (lowercase, '*' as wildcard).")
        for c in r.get("conds", []):
            e = validate_cond(c)
            if e:
                errors.append(f"{where}, host {h}: condition {COND_TYPES.get(c.get('type'), ('?',))[0]}: {e}.")
        key = (h, json.dumps(r.get("conds", []), sort_keys=True))
        if key in seen:
            errors.append(f"{where}: host {h} is listed twice with the same conditions.")
        seen.add(key)
    if s["type"] == "redirect":
        if not URL_RE.match(s.get("target", "")):
            errors.append(f"{where}: redirect target must be an http(s) URL without spaces.")
        if s.get("code") not in (301, 302, 303, 307, 308):
            errors.append(f"{where}: invalid redirect code.")
        return
    if s["type"] != "proxy":
        errors.append(f"{where}: unknown site type.")
        return
    srv_names = set()
    for v in s["servers"]:
        if not NAME_RE.match(v.get("name", "")):
            errors.append(f"{where}: server name '{v.get('name', '')}' is invalid.")
        elif v["name"] in srv_names:
            errors.append(f"{where}: server name {v['name']} is used twice.")
        srv_names.add(v.get("name"))
        m = ADDR_RE.match(v.get("address", ""))
        if not m or not 0 < int(m.group(2)) < 65536:
            errors.append(f"{where}: server {v.get('name')}: address must be host:port.")
        if not OPTS_RE.match(v.get("options", "")):
            errors.append(f"{where}: server {v.get('name')}: options must not contain quotes or '#'.")
        elif set(v.get("options", "").split()) & {"ssl", "check", "verify"}:
            errors.append(f"{where}: server {v.get('name')}: use the checkboxes for ssl/verify/check.")
    if s.get("enabled") and not s["servers"] and not s["redirects"]:
        errors.append(f"{where}: add at least one server (or a path redirect).")
    if s["balance"] not in ("leastconn", "roundrobin", "source", "first"):
        errors.append(f"{where}: invalid load balancing method.")
    if s["cookie"] and not COOKIE_RE.match(s["cookie"]):
        errors.append(f"{where}: invalid cookie name.")
    for k in ("timeout_server", "timeout_tunnel"):
        if s[k] and not TIME_RE.match(s[k]):
            errors.append(f"{where}: invalid {k.replace('_', ' ')} (e.g. 30s, 4h).")
    for p in s["allow_paths"]:
        q = p[1:] if p.startswith("=") else p
        if not PATH_RE.match(q):
            errors.append(f"{where}: allowed path '{p}' must start with / and contain no spaces/quotes/#.")
    _cidrs(s["allow_src"], where + ", allowed clients", errors)
    for r in s["redirects"]:
        if not PATH_RE.match(r.get("path", "")):
            errors.append(f"{where}: redirect path '{r.get('path')}' is invalid.")
        if r.get("match") not in ("exact", "prefix"):
            errors.append(f"{where}: invalid redirect match.")
        if not URL_RE.match(r.get("to", "")):
            errors.append(f"{where}: redirect target '{r.get('to')}' must be an http(s) URL.")
        if r.get("code") not in (301, 302, 303, 307, 308):
            errors.append(f"{where}: invalid redirect code.")
    _lines(s["extra"], where + ", extra directives", errors)


def validate(m):
    errors = []
    g = m["global"]
    for k in ("maxconn", "frontend_maxconn"):
        if not isinstance(g[k], int) or not 1 <= g[k] <= 1000000:
            errors.append(f"Settings: {k} must be a number between 1 and 1000000.")
    for k, v in g["timeouts"].items():
        if not re.match(r"^[a-z-]{3,20}$", k) or not TIME_RE.match(str(v)):
            errors.append(f"Settings: invalid timeout {k} = {v}.")
    for k in ("ssl_options", "ciphers", "ciphersuites", "dhparam"):
        if not OPTS_RE.match(g[k]):
            errors.append(f"Settings: {k} contains invalid characters.")
    if g["dhparam"] and not g["dhparam"].startswith("/"):
        errors.append("Settings: DH parameter file must be an absolute path.")
    _lines(g["extra_global"], "Settings, extra global lines", errors)
    _lines(g["extra_defaults"], "Settings, extra defaults lines", errors)
    l = m["listen"]
    for k in ("http_bind", "https_bind"):
        if not BIND_RE.match(l[k]):
            errors.append(f"Settings: {k} must look like *:80 or 10.0.0.1:443.")
    for k in ("h2_port", "h1_port"):
        if not isinstance(l[k], int) or not 1 <= l[k] < 65536:
            errors.append(f"Settings: {k} must be a port number.")
    if l["h2_port"] == l["h1_port"]:
        errors.append("Settings: internal ports must differ.")
    t = m["tls"]
    if t["source"] not in ("crt-list", "files"):
        errors.append("Settings: invalid certificate source.")
    for f in t["files"]:
        if not f.startswith("/") or not TOKEN_RE.match(f):
            errors.append(f"Settings: certificate file '{f}' must be an absolute path without spaces.")
    h = m["headers"]
    for k in ("server", "hsts", "frame_options"):
        if not HEADER_VAL_RE.match(h[k]):
            errors.append(f"Security: header value for {k} must not contain quotes.")
    for d in h["hsts_domains"]:
        if not DOMAIN_RE.match(d):
            errors.append(f"Security: HSTS domain '{d}' is invalid.")
    sec = m["security"]
    _cidrs(sec["trusted"], "Security, trusted networks", errors)
    for k in ("table_size",):
        if not SIZE_RE.match(sec[k]):
            errors.append("Security: invalid table size (e.g. 100k).")
    for k in ("table_expire", "http_window", "tcp_window"):
        if not TIME_RE.match(sec[k]):
            errors.append(f"Security: invalid time value for {k}.")
    for key in ("rules_https", "rules_http"):
        for r in sec[key]:
            if r.get("action") not in RATE_ACTIONS:
                errors.append("Security: unknown rate limit action.")
            if not (r.get("err_rate") or r.get("req_rate")):
                errors.append("Security: every rate limit rule needs an error or request threshold.")
            for k in ("err_rate", "req_rate"):
                if not isinstance(r.get(k), int) or r[k] < 0:
                    errors.append("Security: thresholds must be positive numbers.")
    for k in ("tcp_conn_rate", "tcp_conn_cur"):
        if not isinstance(sec[k], int) or sec[k] < 0:
            errors.append("Security: connection limits must be numbers (0 = off).")
    for b in sec["sni_block"]:
        for p in [b.get("pattern", "")] + b.get("except", []):
            if not validate_host(p):
                errors.append(f"Security: blocked TLS name '{p}' is invalid.")
    for k in ("http", "https", "tcp"):
        _lines(m["extra"][k], f"Settings, extra {k} frontend lines", errors)
    for raw in m["raw"]:
        first = next((x.strip() for x in raw.split("\n") if x.strip() and not x.strip().startswith("#")), "")
        if not first or first.split()[0] not in SECTION_WORDS:
            errors.append("Settings: each raw section must start with a section keyword (e.g. 'backend X').")
    names = set()
    for s in m["sites"]:
        validate_site(s, errors, names)
    return errors


# ----------------------------------------------------------------------------- rendering helpers
def _glob_regex(host):
    return "^" + ".*".join(p.replace(".", "[.]") for p in host.split("*")) + "$"


def host_expr(fetch, host):
    if "*" not in host:
        return f"{{ {fetch} -m str -i {host} }}"
    if host.startswith("*") and "*" not in host[1:]:
        return f"{{ {fetch} -m end -i {host[1:]} }}"
    if host.endswith("*") and "*" not in host[:-1]:
        return f"{{ {fetch} -m beg -i {host[:-1]} }}"
    return f"{{ {fetch} -m reg -i {_glob_regex(host)} }}"


def cond_expr(c):
    v = " ".join(c["value"].split())
    return ("!" if c.get("neg") else "") + "{ " + COND_TYPES[c["type"]][1].format(v) + " }"


HOSTVAR = "var(txn.host)"


def route_cond(r):
    return " ".join([host_expr(HOSTVAR, r["host"])] + [cond_expr(c) for c in r.get("conds", [])])


def route_sort_key(item):
    idx, r = item
    glob = "*" in r["host"]
    return (glob, -len(r.get("conds", [])), -len(r["host"]) if glob else 0, idx)


def describe_cond(c):
    return ("NOT " if c.get("neg") else "") + COND_TYPES.get(c["type"], (c["type"],))[0].lower() + " " + c["value"]


def _rate_lines(rules, exempt):
    out = []
    for r in rules:
        conds = []
        if r.get("err_rate"):
            conds.append(f"{{ src_http_err_rate gt {r['err_rate']} }}")
        if r.get("req_rate"):
            conds.append(f"{{ src_http_req_rate gt {r['req_rate']} }}")
        if conds:
            out.append(f"http-request {RATE_ACTIONS[r['action']][1]} if {'!trusted ' if exempt else ''}{' '.join(conds)}")
    return out


def _header_lines(h, https):
    out = []
    if https and h["hsts"]:
        line = f'http-response set-header Strict-Transport-Security "{h["hsts"]}"'
        if h["hsts_domains"]:
            ds = " ".join(h["hsts_domains"])
            dots = " ".join("." + d for d in h["hsts_domains"])
            line += f" if {{ {HOSTVAR} -m str -i {ds} }} || {{ {HOSTVAR} -m end -i {dots} }}"
        out.append(line)
    if h["frame_options"]:
        out.append(f'http-response set-header X-Frame-Options "{h["frame_options"]}" if !{{ res.hdr(X-Frame-Options) -m found }}')
    if h["nosniff"]:
        out.append('http-response set-header X-Content-Type-Options "nosniff"')
    if h["server"]:
        out.append(f'http-response set-header Server "{h["server"]}"')
    out.append("http-request set-header X-Real-IP %[src]")
    out.append(f"http-request set-var({HOSTVAR[4:-1]}) req.hdr(host),field(1,:)")
    return out


def _redirect_lines(sites, port80, acme):
    out = []
    for s in sites:
        if s["type"] != "redirect" or (port80 and not s["http"]):
            continue
        loc = s["target"] + ("%[capture.req.uri]" if s["keep_uri"] else "")
        for r in s["routes"]:
            cond = route_cond(r)
            if port80 and acme:
                cond += " !{ path_beg /.well-known/acme-challenge/ }"
            out.append(f"http-request redirect code {s['code']} location {loc} if {cond}")
    return out


def _route_lines(sites, only_hosts=None, port80=False):
    items = []
    for s in sites:
        if s["type"] != "proxy" or (port80 and not s["http"]):
            continue
        for r in s["routes"]:
            if only_hosts is not None and r["host"] not in only_hosts:
                continue
            items.append((len(items), dict(r, backend=s["name"])))
    items.sort(key=route_sort_key)
    return [f"use_backend {r['backend']} if {route_cond(r)}" for _, r in items]


def h1_hosts(sites):
    hosts = []
    for s in sites:
        if s["type"] == "proxy" and s["http1"]:
            for r in s["routes"]:
                if not r.get("conds") and r["host"] not in hosts:
                    hosts.append(r["host"])
    return hosts


def _table(sec, window, tcp=False):
    w = window
    store = f"gpc0,conn_rate({w}),conn_cur,http_req_rate({w}),http_err_rate({w})" if tcp else \
        f"gpc0,conn_rate({w}),http_req_rate({w}),http_err_rate({w})"
    return f"stick-table type ip size {sec['table_size']} expire {sec['table_expire']} store {store}"


def server_line(v, cookie_site):
    parts = ["server", v["name"], v["address"]]
    if v.get("tls"):
        parts += ["ssl", "verify", "required", "ca-file", "@system-ca"] if v.get("verify") else ["ssl", "verify", "none"]
    if v.get("check"):
        parts.append("check")
    opts = v.get("options", "").split()
    if cookie_site and "cookie" not in opts:
        opts += ["cookie", v["name"]]
    return " ".join(parts + opts)


def _site_backend(s):
    out = ["## " + s["description"] if s["description"] else "##", f"backend {s['name']}", "mode http",
           f"balance {s['balance']}"]
    if s["keepalive"]:
        out.append("option http-keep-alive")
    if s["prefer_last"]:
        out.append("option prefer-last-server")
    if s["cookie"]:
        out.append(f"cookie {s['cookie']} insert nocache")
    if s["timeout_server"]:
        out.append(f"timeout server {s['timeout_server']}")
    if s["timeout_tunnel"]:
        out.append(f"timeout tunnel {s['timeout_tunnel']}")
    if s["srvtcpka"]:
        out.append("option srvtcpka")
    out += [l.strip() for l in s["extra"] if l.strip()]
    if s["allow_src"]:
        out.append(f"http-request deny deny_status 403 if !{{ src {' '.join(s['allow_src'])} }}")
    paths = [p for p in s["allow_paths"] if p != "/"]
    if paths and "/" not in s["allow_paths"]:
        for p in paths:
            out.append(f"acl is_allowed path -i {p[1:]}" if p.startswith("=") else f"acl is_allowed path_beg -i {p}")
    for r in s["redirects"]:
        cond = f"{{ path -i {r['path']} }}" if r["match"] == "exact" else f"{{ path -i -m beg {r['path']} }}"
        out.append(f"http-request redirect code {r['code']} location {r['to']} if {cond}")
    if paths and "/" not in s["allow_paths"]:
        out.append("http-request deny deny_status 403 unless is_allowed")
    if s["block"] or not s["servers"]:
        out.append("http-request deny deny_status 403")
    out += [server_line(v, bool(s["cookie"])) for v in s["servers"]]
    return out


def _section(lines, out):
    """lines[0..] may start with comment lines; first non-comment = header; rest indented."""
    header_done = False
    for l in lines:
        if not header_done:
            out.append(l)
            if not l.startswith("#"):
                header_done = True
        elif l == "":
            out.append("")
        else:
            out.append("\t" + l)
    out.append("")


# ----------------------------------------------------------------------------- generator
def render_body(m, ctx):
    """Generate haproxy.cfg (without embedded model).

    ctx: crt_list (path), crt_list_count (int), acme_port (int), denylist (path)
    """
    g, lis, sec, hdr, tls = m["global"], m["listen"], m["security"], m["headers"], m["tls"]
    sites = [s for s in m["sites"] if s.get("enabled", True)]
    out = [HEADER, ""]
    trusted = sec["trusted"]
    exempt = bool(sec["exempt_trusted"] and trusted)
    acme = bool(lis["acme_http01"])

    # global / defaults
    gl = ["global"] + GLOBAL_FIXED + [
        f"ssl-default-bind-ciphers {g['ciphers']}", f"ssl-default-bind-ciphersuites {g['ciphersuites']}",
        f"ssl-default-bind-options {g['ssl_options']}"]
    if g["dhparam"]:
        gl.append(f"ssl-dh-param-file {g['dhparam']}")
    gl += [l.strip() for l in g["extra_global"] if l.strip()]
    _section(gl, out)
    dl = ["defaults"] + DEFAULTS_FIXED
    keys = [k for k in TIMEOUT_ORDER if k in g["timeouts"]] + sorted(k for k in g["timeouts"] if k not in TIMEOUT_ORDER)
    dl += [f"timeout {k} {g['timeouts'][k]}" for k in keys]
    dl += [f"errorfile {c} /etc/haproxy/errors/{c}.http" for c in ERRORFILES]
    dl.append(f"maxconn {g['maxconn']}")
    dl += [l.strip() for l in g["extra_defaults"] if l.strip()]
    _section(dl, out)

    trusted_line = [f"acl trusted src {' '.join(trusted)}"] if trusted else []
    deny_line = f"tcp-request connection reject if {{ src -f {ctx['denylist']} }}"

    # port 80
    fe = ["##", f"frontend {FE_HTTP}", "mode http", f"bind {lis['http_bind']}", "option httplog",
          "option forwardfor", "option httpclose", "capture request header Host len 128", ""]
    fe += trusted_line + [deny_line, _table(sec, sec["http_window"]), "tcp-request connection track-sc0 src"]
    fe += _rate_lines(sec["rules_http"], exempt) + [""]
    fe += _header_lines(hdr, False)
    fe += [l.strip() for l in m["extra"]["http"] if l.strip()]
    fe += _redirect_lines(sites, True, acme)
    if acme:
        fe.append("use_backend ACME-HTTP01 if { path_beg /.well-known/acme-challenge/ }")
    fe += _route_lines(sites, port80=True)
    fe.append("default_backend " + ("NO-SSL" if lis["redirect_to_https"] else "NO-MATCH"))
    _section(fe, out)

    tls_ok = bool(tls["files"]) if tls["source"] == "files" else ctx.get("crt_list_count", 0) > 0
    crt = (" ".join("crt " + f for f in tls["files"]) if tls["source"] == "files"
           else f"crt-list {ctx['crt_list']}")
    hosts1 = h1_hosts(sites)
    if tls_ok:
        fe = ["##", f"frontend {FE_TCP}", f"bind {lis['https_bind']}", "mode tcp",
              f"maxconn {g['frontend_maxconn']}", "option tcplog", ""]
        fe += trusted_line + [deny_line, _table(sec, sec["tcp_window"], tcp=True), "tcp-request connection track-sc0 src"]
        ex = "!trusted " if trusted else ""
        if sec["tcp_conn_rate"]:
            fe.append(f"tcp-request connection reject if {ex}{{ sc0_conn_rate gt {sec['tcp_conn_rate']} }}")
        if sec["tcp_conn_cur"]:
            fe.append(f"tcp-request connection reject if {ex}{{ sc0_conn_cur gt {sec['tcp_conn_cur']} }}")
        fe += ["", "tcp-request inspect-delay 5s"]
        for b in sec["sni_block"]:
            cond = host_expr("req_ssl_sni", b["pattern"]) + "".join(
                " !" + host_expr("req_ssl_sni", e) for e in b.get("except", []))
            fe.append(f"tcp-request content reject if {cond}")
        fe.append("tcp-request content accept if { req_ssl_hello_type 1 }")
        fe += [l.strip() for l in m["extra"]["tcp"] if l.strip()]
        for h in hosts1:
            fe.append(f"use_backend bTCP-443-v1 if {host_expr('req_ssl_sni', h)}")
        fe.append("default_backend bTCP-443")
        _section(fe, out)
        _section(["backend bTCP-443", "mode tcp", f"server local 127.0.0.1:{lis['h2_port']} send-proxy-v2"], out)
        if hosts1:
            _section(["backend bTCP-443-v1", "mode tcp", f"server local 127.0.0.1:{lis['h1_port']} send-proxy-v2"], out)

        def https_fe(name, port, alpn, only):
            fe = ["##", f"frontend {name}", "mode http",
                  f"bind 127.0.0.1:{port} ssl {crt} accept-proxy alpn {alpn}",
                  f"maxconn {g['frontend_maxconn']}", "option httplog", "option forwardfor", "option http-no-delay",
                  "capture request header Host len 128", ""]
            fe += trusted_line + [_table(sec, sec["http_window"]), "tcp-request connection track-sc0 src"]
            fe += _rate_lines(sec["rules_https"], exempt) + [""]
            fe += _header_lines(hdr, True)
            fe += [l.strip() for l in m["extra"]["https"] if l.strip()]
            fe += _redirect_lines(sites, False, False)
            fe += _route_lines(sites, only_hosts=only)
            fe.append("default_backend NO-MATCH")
            _section(fe, out)

        https_fe(FE_H2, lis["h2_port"], "h2,http/1.1", None)
        if hosts1:
            https_fe(FE_H1, lis["h1_port"], "http/1.1", hosts1)
    else:
        out += ["# No TLS certificate available yet: HTTPS frontends are not generated.",
                "# Request and deploy a certificate (Certificates page), then save any change.", ""]

    _section(["##", "backend NO-SSL", "mode http", "redirect scheme https code 302 if !{ ssl_fc }"], out)
    _section(["##", "backend NO-MATCH", "mode http", "http-request deny deny_status 403"], out)
    if acme:
        _section(["## ACME HTTP-01 -> certbot standalone (only listening while a challenge runs)",
                  "backend ACME-HTTP01", "mode http", f"server certbot 127.0.0.1:{ctx['acme_port']}"], out)
    for s in sites:
        if s["type"] == "proxy":
            _section(_site_backend(s), out)
    for raw in m["raw"]:
        out += [l.rstrip() for l in raw.strip("\n").split("\n")] + [""]
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


def render(m, ctx):
    return embed(render_body(m, ctx), m)


def site_by_name(m, name):
    return next((s for s in m["sites"] if s["name"] == name), None)


def suggest_name(host):
    labels = host.replace("*", "wildcard").strip(".").split(".")
    return re.sub(r"[^A-Z0-9_.-]", "-", "-".join(reversed(labels)).upper())[:64]
