"""Configuration model (JSON document) and generator for haproxy.cfg.

The complete haproxy.cfg is generated from the model. The model itself is embedded at the
end of the generated file (compressed, in comment lines), so backups, history, restore and
the sha-based conflict check cover config and model together.
"""
import base64
import copy
import ipaddress
import json
import re
import zlib

MODEL_VERSION = 1
MODEL_MARK = "# ---- HAProxy Admin model (do not edit; used to regenerate this file) ----"
MODEL_PREFIX = "#@hpa-model "
HEADER = ("# Generated by HAProxy Admin. Change it in the web UI; manual edits are detected and can be\n"
          "# imported (Configuration page).")

DEFAULT_CIPHERS = ("ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:"
                   "ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305:"
                   "DHE-RSA-AES128-GCM-SHA256:DHE-RSA-AES256-GCM-SHA384")
DEFAULT_SUITES = "TLS_AES_128_GCM_SHA256:TLS_AES_256_GCM_SHA384:TLS_CHACHA20_POLY1305_SHA256"
TIMEOUT_ORDER = ["connect", "client", "server", "http-keep-alive", "http-request", "tunnel", "queue"]

INTERNAL_BACKENDS = {"NO-SSL", "NO-MATCH", "ACME-HTTP01", "bTCP-443", "bTCP-443-v1"}
FE_HTTP, FE_TCP, FE_H2, FE_H1 = "fHTTP-80", "fTCP-443", "fHTTP-443-v2", "fHTTP-443-v1"

GLOBAL_FIXED = [
    "log /dev/log\tlocal0",
    "log /dev/log\tlocal1 notice",
    "chroot /var/lib/haproxy",
    "stats socket /run/haproxy/admin.sock mode 660 level admin expose-fd listeners",
    "stats timeout 30s",
    "user haproxy",
    "group haproxy",
    "daemon",
    "ca-base /etc/ssl/certs",
    "crt-base /etc/ssl/private",
]
DEFAULTS_FIXED = ["log\tglobal", "mode\thttp", "option\thttplog", "option\tdontlognull"]
ERRORFILES = [400, 403, 408, 500, 502, 503, 504]

# Route conditions: key -> (label, haproxy expression, value hint)
COND_TYPES = {
    "path_beg": ("Path begins with", "path -i -m beg {}", "/api/"),
    "path": ("Path is", "path -i {}", "/favicon.ico"),
    "path_end": ("Path ends with", "path -i -m end {}", ".php"),
    "path_reg": ("Path matches regex", "path -m reg {}", "^/v[0-9]+/"),
    "src": ("Client IP in", "src {}", "10.0.0.0/8 192.168.1.5"),
    "method": ("HTTP method is", "method {}", "GET POST"),
    "query": ("Query string contains", "query -m sub {}", "token="),
}
MULTI_VALUE_CONDS = {"src", "method"}

# Rate limit actions: key -> (label, haproxy action)
RATE_ACTIONS = {
    "drop": ("Drop connection silently", "silent-drop"),
    "deny": ("Reject with 429", "deny deny_status 429"),
    "tarpit": ("Tarpit (slow down, then 500)", "tarpit"),
    "log_silent": ("Stop logging requests", "set-log-level silent"),
    "log_warning": ("Log with level warning", "set-log-level warning"),
}

NAME_RE = re.compile(r"^[A-Za-z0-9_.-]{1,64}$")
HOST_PATTERN_RE = re.compile(r"^[a-z0-9*]([a-z0-9*.-]{0,252})$")
DOMAIN_RE = re.compile(r"^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
ADDR_RE = re.compile(r"^([A-Za-z0-9_.\-]+|\[[0-9a-fA-F:]+\]):(\d{1,5})$")
BIND_RE = re.compile(r"^(\*|[0-9.]+|\[[0-9a-fA-F:]+\]|[A-Za-z0-9.-]+)?:\d{1,5}$")
PATH_RE = re.compile(r"^/[^\s\"'#]*$")
TOKEN_RE = re.compile(r"^[^\s\"'#]+$")
URL_RE = re.compile(r"^https?://[^\s\"'#]+$")
TIME_RE = re.compile(r"^\d{1,7}(us|ms|s|m|h|d)?$")
COOKIE_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
HEADER_VAL_RE = re.compile(r"^[^\"\r\n]*$")
SIZE_RE = re.compile(r"^\d{1,9}[kmg]?$")
OPTS_RE = re.compile(r"^[^\"'#\r\n]*$")
SECTION_WORDS = {"global", "defaults", "frontend", "backend", "listen", "userlist", "peers", "resolvers",
                 "mailers", "program", "http-errors", "ring", "cache"}


